"""D1: evaluation metrics for the checklist (writes docs/ai_evaluation.md).

    python scripts/eval_metrics.py

Inputs (data/eval/):
    labels/*.json        one export per annotator from labeling_tool.html
    gold.json            optional: adjudicated labels {"item|question": "yes"|"no"} after discussion
    answers_jev.json     Jev 1.13 answers (probability of yes), 3 runs
    answers_llm.json     LLM answers (yes/no), 3 runs

Without gold.json, the gold label is the annotators' answer where they agree (yes/no); disagreements
and "unclear" answers are listed in data/eval/disagreements.json for the adjudication meeting and
left out of the scores. Without any labels, only label-free metrics are reported.
"""

import json
import statistics as st
import sys
from collections import defaultdict

from core.ai.checklist import QUESTIONS
from core.config import PROJECT_ROOT

EVAL = PROJECT_ROOT / "data" / "eval"
Q_PRINCIPLE = {q.id: q.principle for q in QUESTIONS}


def cohen_kappa(a: list[str], b: list[str]) -> float | None:
    n = len(a)
    if n == 0:
        return None
    po = sum(x == y for x, y in zip(a, b)) / n
    cats = set(a) | set(b)
    pe = sum((a.count(c) / n) * (b.count(c) / n) for c in cats)
    return None if pe == 1 else (po - pe) / (1 - pe)


def prf(pred: list[bool], gold: list[bool]) -> dict[str, float | int]:
    tp = sum(p and g for p, g in zip(pred, gold))
    fp = sum(p and not g for p, g in zip(pred, gold))
    fn = sum(g and not p for p, g in zip(pred, gold))
    tn = sum(not p and not g for p, g in zip(pred, gold))
    precision = tp / (tp + fp) if tp + fp else 0.0
    recall = tp / (tp + fn) if tp + fn else 0.0
    # F1 is undefined when there is nothing to find and nothing was predicted (tp = fp = fn = 0)
    f1 = None if tp + fp + fn == 0 else (2 * precision * recall / (precision + recall) if precision + recall else 0.0)
    return {"n": len(gold), "tp": tp, "fp": fp, "fn": fn, "tn": tn, "precision": precision, "recall": recall,
            "f1": f1, "accuracy": (tp + tn) / len(gold) if gold else 0.0}


def load_answers(name: str) -> dict | None:
    p = EVAL / f"answers_{name}.json"
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def model_yes(name: str, run: dict, key: str) -> bool:
    v = run[key]
    return v["p_yes"] >= 0.5 if name == "jev" else v["answer"] == "yes"


def pct(x: float) -> str:
    return f"{100 * x:.1f}%"


def main() -> None:
    sys.stdout.reconfigure(encoding="utf-8")
    models = {n: a for n in ("jev", "llm") if (a := load_answers(n))}
    keys = sorted(next(iter(models.values()))["runs"][0]) if models else []
    md = ["# AI evaluation (D1): evidence checklist", "",
          "Generated by `scripts/eval_metrics.py`. Method: [evaluation plan](evaluation_plan.md) (Turkish) and "
          "`core/ai/checklist.py`. Humans, Jev 1.13 and the LLM answer the same 18 yes/no questions "
          "on exactly the same code-selected excerpts (48 items, 177 questions, 11 Verra projects).", ""]

    # --- label-free metrics -------------------------------------------------------------------
    md += ["## Label-free metrics", "", "| | Jev 1.13 | LLM (deepseek-v4.1-flash) |", "|---|---|---|"]
    rows = defaultdict(dict)
    for name, a in models.items():
        runs = a["runs"]
        ans = [[model_yes(name, r, k) for k in keys] for r in runs]
        rows["Yes-rate (run 1)"][name] = pct(sum(ans[0]) / len(keys))
        rows["Same answer in all runs"][name] = pct(sum(len({ans[i][j] for i in range(len(runs))}) == 1
                                                        for j in range(len(keys))) / len(keys))
        rows["Median latency per item"][name] = f"{st.median(v['latency_ms'] for r in runs for v in r.values()):,.0f} ms"
        # cost is recorded per question but billed per item request: count each item once per run
        per_item = {}
        for r in runs:
            for k, v in r.items():
                per_item[(id(r), k.split("|")[0])] = v.get("cost") or 0
        rows["Cost per 1,000 item evaluations"][name] = f"${1000 * sum(per_item.values()) / len(per_item):.2f}"
    if len(models) == 2:
        j = [model_yes("jev", models["jev"]["runs"][0], k) for k in keys]
        l = [model_yes("llm", models["llm"]["runs"][0], k) for k in keys]
        md_agree = pct(sum(x == y for x, y in zip(j, l)) / len(keys))
    for metric, vals in rows.items():
        md.append(f"| {metric} | {vals.get('jev', '-')} | {vals.get('llm', '-')} |")
    if len(models) == 2:
        md += ["", f"Agreement between Jev and the LLM (run 1): **{md_agree}**."]

    # --- human labels -------------------------------------------------------------------------
    label_files = sorted((EVAL / "labels").glob("*.json")) if (EVAL / "labels").exists() else []
    annotators = {}
    for f in label_files:
        d = json.loads(f.read_text(encoding="utf-8"))
        annotators[d["annotator"]] = {f"{x['item_id']}|{x['question_id']}": x["answer"] for x in d["labels"]}
    md += ["", "## Human labels", ""]
    if len(annotators) < 2:
        md += [f"Waiting for labels: {len(annotators)} of 2 annotator files in `data/eval/labels/`."]
        (PROJECT_ROOT / "docs" / "ai_evaluation.md").write_text("\n".join(md) + "\n", encoding="utf-8")
        print("\n".join(md))
        return

    names = sorted(annotators)[:2]
    a1, a2 = annotators[names[0]], annotators[names[1]]
    both = [k for k in keys if a1.get(k) in ("yes", "no") and a2.get(k) in ("yes", "no")]
    kappa = cohen_kappa([a1[k] for k in both], [a2[k] for k in both])
    raw_agree = sum(a1[k] == a2[k] for k in both) / len(both) if both else 0
    unclear = sum(1 for k in keys if "unclear" in (a1.get(k), a2.get(k)))
    md += [f"Annotators: {', '.join(names)}. Both answered yes/no on {len(both)} of {len(keys)} questions; "
           f"raw agreement {pct(raw_agree)}, **Cohen's kappa {kappa:.2f}**; {unclear} questions marked unclear "
           "by at least one annotator.", ""]

    gold_file = EVAL / "gold.json"
    if gold_file.exists():
        gold = json.loads(gold_file.read_text(encoding="utf-8"))
        md.append("Gold labels: adjudicated (`data/eval/gold.json`).")
    else:
        gold = {k: a1[k] for k in both if a1[k] == a2[k]}
        dis = [{"key": k, names[0]: a1.get(k), names[1]: a2.get(k)} for k in keys if k not in gold]
        (EVAL / "disagreements.json").write_text(json.dumps(dis, indent=1) + "\n", encoding="utf-8")
        md.append(f"Gold labels: questions where both annotators agree ({len(gold)}); {len(dis)} disagreements or "
                  "unclear answers listed in `data/eval/disagreements.json` for adjudication.")
    gkeys = [k for k in keys if gold.get(k) in ("yes", "no")]
    g = [gold[k] == "yes" for k in gkeys]
    md += ["", f"Gold set: {len(gkeys)} questions, {sum(g)} yes ({pct(sum(g) / len(g))}).", "",
           "### Overall (positive class = evidence present)", "",
           "| Model | Precision | Recall | F1 | Accuracy | Macro-F1 over questions |", "|---|---|---|---|---|---|"]
    per_q = {}
    for name, a in models.items():
        pred = [model_yes(name, a["runs"][0], k) for k in gkeys]
        m = prf(pred, g)
        qf1 = []
        for q in QUESTIONS:
            idx = [i for i, k in enumerate(gkeys) if k.endswith("|" + q.id)]
            if idx:
                qm = prf([pred[i] for i in idx], [g[i] for i in idx])
                if qm["f1"] is not None:
                    qf1.append(qm["f1"])
                per_q.setdefault(q.id, {})[name] = qm
        md.append(f"| {name} | {m['precision']:.2f} | {m['recall']:.2f} | {m['f1']:.2f} | {m['accuracy']:.2f} | "
                  f"{st.mean(qf1):.2f} ({len(qf1)} questions with evidence) |")
    if "jev" in models:
        probs = [models["jev"]["runs"][0][k]["p_yes"] for k in gkeys]
        brier = st.mean((p - gi) ** 2 for p, gi in zip(probs, g))
        md += ["", f"Jev calibration: Brier score **{brier:.3f}** (0 is perfect; always answering the base rate "
               f"would score {st.mean((sum(g) / len(g) - gi) ** 2 for gi in g):.3f})."]
    md += ["", "### Per question (F1)", "", "| Question | Principle | n | " + " | ".join(models) + " |",
           "|---|---|---|" + "---|" * len(models)]
    for q in QUESTIONS:
        if q.id in per_q:
            n = next(iter(per_q[q.id].values()))["n"]
            md.append(f"| {q.id} | {q.principle} | {n} | " +
                      " | ".join("n/a" if per_q[q.id][m]["f1"] is None else f"{per_q[q.id][m]['f1']:.2f}"
                                 for m in models) + " |")
    md += ["", "Caveats: labels come from the team using a written guide, not from domain experts; questions "
           "measure whether evidence is *present* in the excerpt, not whether it is true."]
    (PROJECT_ROOT / "docs" / "ai_evaluation.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print("\n".join(md))


if __name__ == "__main__":
    main()
