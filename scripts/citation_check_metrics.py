"""Summarise the citation check (writes docs/citation_check.md).

    python scripts/citation_check_metrics.py

Reads data/eval/citation_check/{units.json, key.json, labels/*.json}. The question measured: when the checklist,
given a 30,000-character excerpt instead of the 2,500-character one, finds evidence the gold set had marked
absent, is the cited paragraph really evidence? Decoys (paragraphs the model did not cite) show how often the
annotator says "yes" without a model citation behind it.
"""

import json
import math
import sys
from collections import defaultdict

from core.config import PROJECT_ROOT

CC = PROJECT_ROOT / "data" / "eval" / "citation_check"


def wilson(k: int, n: int, z: float = 1.96) -> tuple[float, float]:
    if n == 0:
        return (0.0, 1.0)
    p = k / n
    c = (p + z * z / (2 * n)) / (1 + z * z / n)
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / (1 + z * z / n)
    return (max(0.0, c - h), min(1.0, c + h))


def share(k: int, n: int) -> str:
    lo, hi = wilson(k, n)
    return f"{k}/{n} ({100 * k / n:.0f}%, 95% interval {100 * lo:.0f}-{100 * hi:.0f}%)" if n else "n/a"


def main() -> None:
    sys.stdout.reconfigure(encoding="utf-8")
    key = json.loads((CC / "key.json").read_text(encoding="utf-8"))["units"]
    files = {}
    for f in sorted((CC / "labels").glob("*.json")):
        d = json.loads(f.read_text(encoding="utf-8"))
        files[d["annotator"]] = (d.get("kind", "human"), {x["uid"]: x["answer"] for x in d["labels"]})
    md = ["# Citation check", "", "Generated by `scripts/citation_check_metrics.py` from "
          "[`data/eval/citation_check/`](../data/eval/citation_check/).", "",
          "On 30,000-character excerpts the checklist answered \"yes\" on questions the gold set marks \"no\" for the "
          "2,500-character excerpt, each citing a paragraph from the extra text. Each cited paragraph (up to two per "
          "question) was judged on its own, mixed with length-matched decoys the model did not cite, without "
          "showing which was which.", ""]
    summary = {}
    for name, (kind, labels) in files.items():
        by_q, src = defaultdict(list), defaultdict(list)
        for uid, v in key.items():
            if uid not in labels or labels[uid] == "unclear":
                continue
            src[v["source"]].append(labels[uid] == "yes")
            if v["source"] == "model_citation":
                by_q[f"{v['item_id']}|{v['question_id']}"].append(labels[uid] == "yes")
        confirmed = sum(any(x) for x in by_q.values())
        summary[name] = {"kind": kind, "questions": len(by_q), "confirmed": confirmed,
                         "confirmed_ci95": [round(x, 4) for x in wilson(confirmed, len(by_q))],
                         "decoys": len(src["decoy"]), "decoys_yes": sum(src["decoy"])}
        md += [f"## {name} ({kind}, {len(labels)} units labelled)", "",
               f"- Questions whose new \"yes\" is confirmed by a cited paragraph: **{share(confirmed, len(by_q))}**",
               f"- Cited paragraphs judged to be evidence: {share(sum(src['model_citation']), len(src['model_citation']))}",
               f"- Decoys judged to be evidence: {share(sum(src['decoy']), len(src['decoy']))}", ""]
    humans = [n for n, (k, _) in files.items() if k == "human"]
    ais = [n for n, (k, _) in files.items() if k == "ai"]
    for h in humans:
        for a in ais:
            hl, al = files[h][1], files[a][1]
            both = [u for u in hl if u in al and hl[u] != "unclear" and al[u] != "unclear"]
            agree = sum(hl[u] == al[u] for u in both)
            md += [f"Human check of the AI labels ({h} vs {a}): agreement on {share(agree, len(both))} of the units "
                   "both labelled.", ""]
            summary[a]["human_check"] = {"annotator": h, "units": len(both), "agree": agree}
    md += ["Caveats: \"evidence\" means the paragraph contains what the question asks for, not that it is true. "
           "Questions still answered \"no\" on the long excerpt were not re-checked, so recall on the long excerpt "
           "is known only for the gold set's positives."]
    (CC / "summary.json").write_text(json.dumps(summary, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    out = PROJECT_ROOT / "docs" / "citation_check.md"
    out.write_text("\n".join(md) + "\n", encoding="utf-8")
    print("\n".join(md))


if __name__ == "__main__":
    main()
