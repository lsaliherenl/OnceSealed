"""Run the deterministic data checks (core/checks) for every project and publish the results.

Writes checks/<project>.json (published next to reports/, with the inputs' hashes so anyone holding the same
PDFs and OffsetsDB snapshot gets the same result) and docs/data_checks.md (summary table). Needs the PDFs in
samples/pdfs/ and the OffsetsDB snapshot in data/raw/offsetsdb/; no API key.

    python scripts/run_checks.py [VCS985 ...]
"""

import json
import sys

import pymupdf

from core.ai.pdf_extract import extract_tables
from core.ai.sources import ROLES, load_manifest
from core.checks.run import run_checks
from core.config import PROJECT_ROOT

OUT = PROJECT_ROOT / "checks"
DOC = PROJECT_ROOT / "docs" / "data_checks.md"
ICON = {"pass": "pass", "flag": "**flag**", "info": "info", "not_available": "n/a"}


def main() -> None:
    wanted = set(sys.argv[1:])
    projects = [p for p in load_manifest() if not wanted or p.project_id in wanted]
    OUT.mkdir(exist_ok=True)
    results = []
    for p in projects:
        files = [f for f in p.files if f.status() == "present"]
        missing = [f.local_path for f in p.files if f.status() != "present"]
        if missing:
            print(f"{p.project_id}: skipping files not present or not matching the manifest: {missing}")
        tables = {f.local_path: extract_tables(f.path) for f in files}
        result = run_checks(p, tables)
        for d in result["inputs"]["documents"]:
            with pymupdf.open(PROJECT_ROOT / d["file"]) as doc:
                texts = [doc[i].get_text() for i in range(doc.page_count)]
            d.update(pages=len(texts), pages_without_text=[i + 1 for i, t in enumerate(texts) if len(t.strip()) < 20],
                     tables=len(tables[d["file"]]))
        (OUT / f"{p.project_id}.json").write_text(json.dumps(result, indent=1, ensure_ascii=False) + "\n",
                                                  encoding="utf-8")
        results.append(result)
        print(p.project_id, " ".join(f"{c['id']}={c['status']}" for c in result["checks"]))
    if not wanted:
        write_summary(results)


def write_summary(results: list[dict]) -> None:
    ids = [c["id"] for c in results[0]["checks"]]
    titles = {c["id"]: c["title"] for c in results[0]["checks"]}
    lines = [
        "# Data checks (deterministic, no AI)",
        "",
        "Generated by `scripts/run_checks.py` from the project documents listed in `samples/manifest.json` and the "
        f"CarbonPlan OffsetsDB snapshot of {results[0]['inputs']['offsetsdb_snapshot']}. Per-project results with "
        "every number, page and table id: `checks/<project>.json`.",
        "",
        "A **flag** is a lead for a reviewer, not a finding of wrongdoing; **n/a** means the input was missing and "
        "is never counted as a pass.",
        "",
        "| Project | " + " | ".join(titles[i] for i in ids) + " |",
        "|---|" + "---|" * len(ids),
    ]
    for r in results:
        by = {c["id"]: c for c in r["checks"]}
        lines.append(f"| {r['project_id']} | " + " | ".join(ICON[by[i]["status"]] for i in ids) + " |")
    lines += ["", "## Findings", ""]
    for r in results:
        for c in r["checks"]:
            if c["status"] in ("flag", "info") and c["id"] != "document_coverage":
                lines.append(f"- **{r['project_id']}**, {c['title'].lower()}: {c['summary']}")
    lines += ["", "## Documents read", "", "| Project | Read | Pages | Tables | Pages without text | Not read |",
              "|---|---|---|---|---|---|"]
    for r in results:
        docs = r["inputs"]["documents"]
        cov = next(c for c in r["checks"] if c["id"] == "document_coverage")["details"]
        lines.append(f"| {r['project_id']} | " + ", ".join(ROLES[d["role"]] for d in docs)
                     + f" | {sum(d['pages'] for d in docs)} | {sum(d['tables'] for d in docs)}"
                     + f" | {sum(len(d['pages_without_text']) for d in docs)} | "
                     + (", ".join(ROLES[m] for m in cov["missing"]) or "-") + " |")
    DOC.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {DOC.relative_to(PROJECT_ROOT)}")


if __name__ == "__main__":
    main()
