"""Generate tests/vectors.json: shared test vectors for Python (pytest), Solidity (Foundry) and the browser (web).

Deterministic: running it again produces the same file. Every suite recomputes the values from the inputs and
compares, so an encoding change on any side fails CI:

  text_ids, commitments  tests/test_privacy.py, contracts/test/Vectors.t.sol, web/tests/parity.test.ts
  lei_checks, buyer_ids  LEI validation and its normalisation (Python and browser)
  receipts               the offline receipt check (core.privacy.receipt.receipt_commitment, web/src/lib/hashing.ts)
  canonical_json         the report hash, keccak256 of canonical JSON (core.hashing, web/src/lib/hashing.ts)

    python scripts/gen_vectors.py
"""

import json
import random

from eth_utils import keccak

from core.config import PROJECT_ROOT
from core.hashing import canonical_json, hash_json
from core.privacy.commitment import commitment, to_hex
from core.privacy.identity import buyer_id, fictional_lei, is_valid_lei, text_id
from core.privacy.receipt import receipt_commitment

CASES = [
    ("VCS1477|vector-batch-A", 1, 1),
    ("VCS1851|vector-batch-B", 100, 199),
    ("VCS138|vector-batch-C", 18_446_744_073_709_551_000, 18_446_744_073_709_551_615),  # near uint64 max
]

# Values whose canonical form differs between naive JSON writers: float formatting (1.0, 1e-05, 1e+16), key order
# by code point (U+FF01 sorts before an emoji in Python, after it in UTF-16), escapes, non-ASCII text, big integers.
CANONICAL_CASES = [
    {"b": 1, "a": [1.0, 0.0, -0.5, 0.0001, 1e-05, 1e16, 1e15, 0.1 + 0.2, 123456789.125, 2 ** 64, -7]},
    {"text": "Çevre · “quotes” – dash\nnew line\ttab \\ slash \"q\" \u0001 \u007f é \U0001f600",
     "z": None, "y": True, "x": False},
    {"！": 1, "\U0001f600": 2, "a": {"B": [], "_": {}, "A": ""}},
]


def _flip_check_digits(lei: str) -> str:
    return lei[:18] + f"{(int(lei[18:]) + 1) % 100:02d}"


def _receipt_case(name: str, receipt: dict) -> dict:
    try:
        return {"name": name, "receipt": receipt, "commitment": receipt_commitment(receipt), "error": False}
    except ValueError:
        return {"name": name, "receipt": receipt, "commitment": None, "error": True}


def main() -> None:
    rng = random.Random(20261014)
    text_ids = [{"text": t, "id": to_hex(text_id(t))} for t in ["VCS1477", "VCS1851", "VCS138", "VCS2505"]]
    commitments = []
    for i, (batch_key, start, end) in enumerate(CASES):
        lei = fictional_lei(rng)
        salt = keccak(text=f"oncesealed-vector-salt-{i}")
        batch_id = text_id(batch_key)
        commitments.append({
            "lei": lei,
            "buyer_id": to_hex(buyer_id(lei)),
            "salt": to_hex(salt),
            "batch_key": batch_key,
            "batch_id": to_hex(batch_id),
            "start": start,
            "end": end,
            "commitment": to_hex(commitment(buyer_id(lei), salt, batch_id, start, end)),
        })

    leis = [c["lei"] for c in commitments]
    buyers = [b["lei"] for b in json.loads((PROJECT_ROOT / "data" / "demo_buyers.json").read_text("utf-8"))["buyers"]]
    candidates = leis + buyers[:3] + [
        leis[0].lower(), f" {leis[1]} ", _flip_check_digits(leis[0]), _flip_check_digits(buyers[0]),
        leis[0][:19], leis[0] + "0", leis[0][:18] + "9A", leis[0][:5] + "-" + leis[0][6:], "", "00000000000000000000",
    ]
    lei_checks = [{"lei": s, "valid": is_valid_lei(s)} for s in candidates]
    buyer_ids = [{"input": s, "buyer_id": to_hex(buyer_id(s))} for s in [leis[0], leis[0].lower(), f"  {leis[1]}\t"]]

    v = commitments[1]
    base = {"retirement_id": 7, "chain_id": 11155111, "contract": "0x" + "11" * 20, "batch_id": v["batch_id"],
            "start": v["start"], "end": v["end"], "lei": v["lei"], "buyer_id": v["buyer_id"], "salt": v["salt"]}
    receipts = [
        _receipt_case("valid", base),
        _receipt_case("lei_lowercase", {**base, "lei": base["lei"].lower()}),
        _receipt_case("buyer_id_of_another_lei", {**base, "buyer_id": commitments[0]["buyer_id"]}),
        _receipt_case("lei_check_digits_wrong", {**base, "lei": _flip_check_digits(base["lei"])}),
        _receipt_case("salt_changed", {**base, "salt": commitments[0]["salt"]}),
        _receipt_case("range_changed", {**base, "end": base["end"] + 1}),
        _receipt_case("range_reversed", {**base, "start": base["end"], "end": base["start"]}),
    ]
    canonical = [{"text": json.dumps(obj, indent=2, ensure_ascii=False),
                  "canonical": canonical_json(obj).decode("utf-8"), "hash": hash_json(obj)} for obj in CANONICAL_CASES]

    out = {
        "version": 2,
        "note": "Generated by scripts/gen_vectors.py. LEIs are fictional (valid check digits, not registered).",
        "text_ids": text_ids,
        "commitment_count": len(commitments),
        "commitments": commitments,
        "lei_checks": lei_checks,
        "buyer_ids": buyer_ids,
        "receipts": receipts,
        "canonical_json": canonical,
    }
    path = PROJECT_ROOT / "tests" / "vectors.json"
    path.write_text(json.dumps(out, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"wrote {path.relative_to(PROJECT_ROOT)} ({len(commitments)} commitments, {len(lei_checks)} LEIs, "
          f"{len(receipts)} receipts, {len(canonical)} canonical JSON cases)")


if __name__ == "__main__":
    main()
