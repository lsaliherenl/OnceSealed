"""Generate tests/vectors.json: shared test vectors for Python (pytest) and Solidity (Foundry).

Deterministic: running it again produces the same file. Both test suites recompute
every value from the inputs and compare, so an encoding change on either side fails CI.

    python scripts/gen_vectors.py
"""

import json
import random

from eth_utils import keccak

from core.config import PROJECT_ROOT
from core.privacy.commitment import commitment, to_hex
from core.privacy.identity import buyer_id, fictional_lei, text_id

CASES = [
    ("VCS1477|vector-batch-A", 1, 1),
    ("VCS1851|vector-batch-B", 100, 199),
    ("VCS138|vector-batch-C", 18_446_744_073_709_551_000, 18_446_744_073_709_551_615),  # near uint64 max
]


def main() -> None:
    rng = random.Random(20261014)
    text_ids = [{"text": t, "id": to_hex(text_id(t))} for t in ["VCS1477", "VCS1851", "VCS138", "VCS2505"]]
    commitments = []
    for i, (batch_key, start, end) in enumerate(CASES):
        lei = fictional_lei(rng)
        salt = keccak(text=f"oncesealed-vector-salt-{i}")
        batch_id = text_id(batch_key)
        commitments.append({
            "lei": lei,
            "buyer_id": to_hex(buyer_id(lei)),
            "salt": to_hex(salt),
            "batch_key": batch_key,
            "batch_id": to_hex(batch_id),
            "start": start,
            "end": end,
            "commitment": to_hex(commitment(buyer_id(lei), salt, batch_id, start, end)),
        })
    out = {
        "version": 1,
        "note": "Generated by scripts/gen_vectors.py. LEIs are fictional (valid check digits, not registered).",
        "text_ids": text_ids,
        "commitment_count": len(commitments),
        "commitments": commitments,
    }
    path = PROJECT_ROOT / "tests" / "vectors.json"
    path.write_text(json.dumps(out, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {path.relative_to(PROJECT_ROOT)} ({len(commitments)} commitments)")


if __name__ == "__main__":
    main()
